subroutine save_bas_molpro(ilog,ibas,natom,tag,ctmp)
 implicit double precision (a-h,o-z)
 parameter(au2ang=0.529177249d0)
 character*(*) tag,ctmp
 character*(3) :: atoms
 allocatable   :: xyz(:)

 open(ibas,file="mbas.tmp")
 rewind(ibas)
