!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! read Bdf's coordinates and basis functions from ilog, and save them to ibas.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine save_bas_bdf(ilog,ibas,natom,tag,ctmp)
 implicit double precision (a-h,o-z)
 character*(*) tag,ctmp
 logical       :: ifecp
 character*(3) :: atoms
 allocatable   :: xyz(:)

 open(ibas,file="mbas.tmp")
 rewind(ibas)
 rewind(ilog)

 do while(.true.)
   read(ilog,"(a200)",err=6000,end=6000) ctmp
   if(index(ctmp,'MCSCF') == 45) exit
 end do

 tag=" Atom           Cartcoord(Bohr)                 Charge"
 do while(.true.)
   read(ilog,"(a200)",err=6010,end=6010) ctmp
   if(index(ctmp,tag(1:54)) == 1) exit
 end do

 allocate(xyz(3))

 write(ibas,"('# XYZ')")
 do iatom = 1, natom
   read(ilog,*) atoms, xyz(:), za
   iza = nint(za)
   ! Atom, iza, xyz in au
   write(ibas,"(a3,i5,3f18.9)") atoms, iza, xyz(:)
 end do

 deallocate(xyz)

 rewind(ilog)

 tag=" Printing basis sets for checking ...."
 do while(.true.)
   read(ilog,"(a200)",err=6020,end=6020) ctmp
   if(index(ctmp,tag(1:38)) == 1) exit
 end do
 tag=" Basis functions in Orca format."
 read(ilog,"(/,a200,/)",err=6020,end=6020) ctmp
 if(index(ctmp,tag(1:32)) < 1) goto 6030

 write(ibas,"('# BAS')")
 ifecp = .false.
 tag=" Molecular center of massNewECP end"
 do while(.true.)
   read(ilog,"(a200)",err=6040,end=6040) ctmp
   if(index(ctmp,tag(1:25)) == 1) then
     exit
   else if(index(ctmp,tag(26:32)) == 1) then
     ifecp = .true.
   else if(ifecp .and. index(ctmp,tag(33:35)) == 1) then
     ifecp = .false.
   end if
   ! neglect ECP
   if(.not. ifecp .and. index(ctmp,tag(33:35)) == 0) write(ibas,"(a)") trim(ctmp)
 end do

 tag="  Number of symmery unique centers:"
 do while(.true.)
   read(ilog,"(a200)",err=6050,end=6050) ctmp
   if(index(ctmp,tag(1:35)) == 1) then
     read(ctmp(36:),*) nucent
     if(nucent < natom)  call XError('Symmetry equivalent atoms are not supported! You have to use a lower symmetry.')
     exit
   end if
 end do

 return

 6000  call XError("Standard MCSCF output cannot be found in sub. save_bas_bdf!")
 6010  call XError("Cartcoord cannot be found in sub. save_bas_bdf!")
 6020  call XError("Basis functions cannot be found in sub. save_bas_bdf!")
