 ! determine the program: 0 = molpro, 1 = bdf.
 subroutine chkpro(ipro,imos,ctmp)
  implicit real(kind=8) (a-h,o-z)
  character*15 ctmp

  rewind(imos)

  do i = 1, 2
    read(imos,"(a15)") ctmp
    if(index(ctmp,'BEGIN_DATA,') > 0) then
      ipro = 0
    else if(index(ctmp,'$MOCOEF  1') > 0) then
      ipro = 1
    end if
  end do

  return
 end subroutine chkpro

 ! check file
 subroutine chkfile(fname,imod1,ifopen,imod2,ifexist)
  implicit real(kind=8) (a-h,o-z)
  character*(*) fname
  logical :: ifopen, ifexist

  if(imod1 == 1 .and. ifopen) then
    write(*,"(/,'  File: ',a)") trim(fname)
    call XError("This file has been opened.")
  end if

  if(imod2 == 1 .and. .not. ifexist) then
    write(*,"(/,'  File: ',a)") trim(fname)
    call XError("This file does not exist.")
  end if

  return
 end subroutine chkfile

end subroutine RdArg

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! Check whether the string contains a real number (imod >= 0) or an integer (imod < 0).
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine chknumber(imod,cha)
 implicit real(kind=8) (a-h,o-z)
 character*(*) :: cha

 ndot = 0
 lenth = len_trim(cha)
 do i = 1, lenth
   if(i == 1 .and. lenth > 1 .and. (cha(1:1) == '+' .or. cha(1:1) == '-')) cycle

   j = ichar(cha(i:i))
   if(i == lenth .and. (j < 48 .or. j > 57)) call XError("CHA does not contain a normal number.")

   if(imod >= 0) then
     if((j < 48 .or. j > 57) .and. cha(i:i) /= '.') call XError("CHA does not contain a normal real number.")
     if(cha(i:i) == '.') ndot = ndot + 1
   else
     if((j < 48 .or. j > 57)) call XError("CHA does not contain a normal integer.")
   end if
 end do
 if(ndot > 1) call XError("More than one decimal point in CHA.")

 return
end subroutine chknumber

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! position of the first non-space character in a string.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function nonspace(string)
 implicit double precision (a-h,o-z)
 character*(*) string

 length=LEN_TRIM(string)
 if(length <= 1) then
   i=length
 else
   do i=1,length
     if(string(i:i) /= ' ') exit
   end do
 endif

 nonspace=i

 return
end function nonspace

