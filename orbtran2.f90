!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! The OrbTran-II program is used to convert pseudo-canonical molecular orbital (PCMO) data files generated by state-average MCSCF
! calculations with Molpro or BDF into formats of other programs, in order to compare results of multireference methods like MRCI,
! CASPT2, and NEVPT2.
!
! The OrbTran-II program builds on the OrbTran program developed in 2020. OrbTran was designed to convert Molpro's or BDF's PCMO
! files to MOLCAS or COLUMBUS(argos) calculations. Although there were existing tools with similar functions, such as MOKIT,
! OrbTran was developed specifically for MCSCF calculations involving atoms in C2v or D2h symmetry and heteronuclear diatomic
! molecules in C2 or C2v symmetry, which however limited its applicability to general molecules.
!
! OrbTran-II is the successor to OrbTran, extending support to general molecules. It provides the following features.
!
! 1) Reads PCMOs.
!    PCMOs may be computed by Molpro's MULTI module or BDF's MCSCF module. All eight Abelian point groups and spherical Gaussian
!    basis functions up to l = 6 (i) have been supported.
! 2) Writes PCMOs into a text file.
!    2.1 RasOrb format used by BDF, Molcas, or Molpro.
!    2.2 MOLEKEL format used by ORCA (up to h-functions). Symmetry-equivalent atoms are not supported.
!    2.3 MOLDEN format (up to h-functions). Symmetry-equivalent atoms are not supported.
!    2.4 A new RasOrb file with adjusted PCMO coefficients.
!
! For various options and explanations, refer to the subroutine RdArg.
!
! Jan. 24, 2026. The first version of OrbTran-II.
! Feb. 01, 2026. (partly) support for saving as mkl format for ORCA calculations and molden format.
! Feb. 18, 2026. Check whether the files are opened repeatedly.
! Jun. 05, 2026. Introduce a unified output option: -out.
! Jun. 27, 2026. Add a new option p for MO operations.
! Jul. 02, 2026. Add a new option P for MO operations.
! Jul. 08, 2026. A typo in Molden [GTO].
! Sep. 22, 2026. BDF upgraded the printing of basis functions in ORCA format, so the program has to be revised accordingly.
!
! Note
! 1) The atoms computed by different programs must be in the same ordering and the same orientation.
! 2) Contractions of the basis set must be exactly the same. e.g., contractions of cc-pVQZ in BDF (Gaussian-style) and in Molpro
!    (standard-style) are different.
! 3) Symmetry-equivalent atoms are not supported for saving Molekel and Molden files.
! 4) Some symmetries may be not supported for ORCA (mkl) since symmetry generators and orientations cannot be well controlled.
! 5) For BDF, you need to use the GEN() function after the COMPASS-module's GROUP keyword to specify symmetry generators. It is
!    not recommended to directly specify the point group name (unless you are familiar with the details of molecular coordinates,
!    symmetry, and basis contractions), as this may cause unexpected rotation of molecular coordinates. For sf-X2C relativistic
!    calculations, it may also be necessary to modify the nuclear charge distribution model (NUCLEAR) and the speed of light
!    (CLIGHT) in the XUANYUAN module in order to be consistent with the settings of other programs.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
program orbtran2
 implicit real(kind=8) (a-h,o-z)
 parameter (nmode=6, ilog=41, imos=42, iopr=43, iorb=51, igto=52, ibas=53, inew=61, iras=62, ibdf=63, imol=64, imkl=65, imdn=66)
 character*200 :: ctmp,tag
 logical       :: ifopen
 dimension     :: nbas(8), imode(nmode)
 allocatable   :: cmo(:), occ1(:), occ2(:), scr(:), ibmap(:), irrep(:), infobs(:,:)
 allocatable   :: infshl(:,:), occtmp(:), cmofull(:,:)    ! required by -mkl & -mdn

!---------------------------------------------------------------------------------------------------------------------------------
! 1. read arguments.
!---------------------------------------------------------------------------------------------------------------------------------
 call RdArg(ipro,ilog,imos,iopr,inew,iras,ibdf,imol,imkl,imdn,istp,nmode,imode,ctmp)

!---------------------------------------------------------------------------------------------------------------------------------
! 2. check natom, symmetry, and nbas. For mkl, coordinates and basis functions are also read.
!---------------------------------------------------------------------------------------------------------------------------------
 if(ipro == 0) then
   call chk_molpro(ilog,iorb,natom,nsym,nbas,igrp,istp,tag,ctmp)
   if(imode(5) == 1 .or. imode(6) == 1) call save_bas_molpro(ilog,ibas,natom,tag,ctmp)
 else if(ipro == 1) then
   call chk_bdf(ilog,iorb,natom,nsym,nbas,igrp,istp,tag,ctmp)
   if(imode(5) == 1 .or. imode(6) == 1) call save_bas_bdf(ilog,ibas,natom,tag,ctmp)
 end if
 close(ilog)

 ntotbs = 0
 mbas = 8
 ncoe = 0
 do i = 1, nsym
   ntotbs = ntotbs + nbas(i)
   mbas = max(mbas,nbas(i))
   ncoe = ncoe + nbas(i)**2
 end do

 !allocate(cmo(ncoe),occ1(ntotbs),occ2(ntotbs),scr(mbas*mbas))
 !allocate(irrep(nsym),infobs(3,ntotbs),ibmap(mbas))
 ! -mkl & -mdn require larger dimensions of scr and ibmap
 allocate(cmo(ncoe),occ1(ntotbs),occ2(ntotbs),scr(ntotbs*ntotbs))
 allocate(irrep(nsym),infobs(3,ntotbs),ibmap(ntotbs))

!---------------------------------------------------------------------------------------------------------------------------------
! 3. r/w occupation numbers and basis function pattern
!---------------------------------------------------------------------------------------------------------------------------------
 if(ipro == 0) then
   call rd_patt_molpro(iorb,igto,ntotbs,nsym,nbas,occ1,tag,ctmp)
 else if(ipro == 1) then
   call rd_patt_bdf(iorb,igto,nsym,nbas,tag,ctmp)
 end if
 close(iorb,status='delete')

!---------------------------------------------------------------------------------------------------------------------------------
! 4. read basis function patterns
!---------------------------------------------------------------------------------------------------------------------------------
 call bas_patt(igto,ntotbs,maxlq,infobs)
 close(igto,status='delete')

!---------------------------------------------------------------------------------------------------------------------------------
! 5. read MO coefficients in row vector
!---------------------------------------------------------------------------------------------------------------------------------
 if(ipro == 0) then
   call mos_molpro(imos,nsym,nbas,cmo)
 else if(ipro == 1) then
   call mos_bdf(imos,ntotbs,nsym,nbas,cmo,occ1,tag,ctmp)
 end if
 close(imos)

!---------------------------------------------------------------------------------------------------------------------------------
! 6. save a new MO coefficient file
!---------------------------------------------------------------------------------------------------------------------------------
 ! molpro/bdf --> molcas
 if(imode(2) == 1) then
   call symmap(ipro,1,igrp,irrep)
   call pr_head_ras(iras,nsym,nbas,irrep,ctmp)
   loff = 0
   do isym = 1, nsym
     isym1 = irrep(isym)
     if(nbas(isym1) < 1) cycle
     moff = 0
     noff = 0
     do i = 1, isym1-1
       moff = moff + nbas(i)
       noff = noff + nbas(i)**2
     end do
     call basmap(natom,maxlq,2,nbas(isym1),infobs(1,moff+1),ibmap)
     call reorderbs(nbas(isym1),.true.,ibmap,occ1(moff+1),occ2(loff+1),cmo(noff+1),scr)
     ! now MOs saved in scr are in column vector
     call wr_mos(2,iras,isym,nbas(isym1),scr)
     loff = loff + nbas(isym1)
   end do
   call wr_occ_end(2,iras,ntotbs,nsym,nbas,occ2)
   close(iras)
 end if

 ! molpro --> bdf
 if(imode(3) == 1) then
   call symmap(ipro,0,igrp,irrep)
   call pr_head_new(1,ibdf,ctmp)
   loff = 0
   do isym = 1, nsym
     isym1 = irrep(isym)
     if(nbas(isym1) < 1) cycle
     moff = 0
     noff = 0
     do i = 1, isym1-1
       moff = moff + nbas(i)
       noff = noff + nbas(i)**2
     end do
     call basmap(natom,maxlq,1,nbas(isym1),infobs(1,moff+1),ibmap)
     call reorderbs(nbas(isym1),.true.,ibmap,occ1(moff+1),occ2(loff+1),cmo(noff+1),scr)
     ! now MOs saved in scr are in column vector
     call wr_mos(1,ibdf,isym,nbas(isym1),scr)
     loff = loff + nbas(isym1)
   end do
   call wr_occ_end(1,ibdf,ntotbs,nsym,nbas,occ2)
   close(ibdf)
 end if

 ! bdf --> molpro
 if(imode(4) == 1) then
   call symmap(ipro,0,igrp,irrep)
   call pr_head_new(0,imol,ctmp)
   loff = 0
   do isym = 1, nsym
     isym1 = irrep(isym)
     if(nbas(isym1) < 1) cycle
     moff = 0
     noff = 0
     do i = 1, isym1-1
       moff = moff + nbas(i)
       noff = noff + nbas(i)**2
     end do
     call basmap(natom,maxlq,0,nbas(isym1),infobs(1,moff+1),ibmap)
     call reorderbs(nbas(isym1),.false.,ibmap,occ1(moff+1),occ2(loff+1),cmo(noff+1),scr)
     ! now MOs saved in scr are in row vector
     call wr_mos(0,imol,isym,nbas(isym1),scr)
     loff = loff + nbas(isym1)
   end do
   call wr_occ_end(0,imol,ntotbs,nsym,nbas,occ2)
   close(imol)
 end if

 if(imode(5) == 1 .or. imode(6) == 1) then
   allocate(infshl(2,ntotbs), occtmp(ntotbs), cmofull(ntotbs,ntotbs))    ! ntotbs > nshell is large enough for infshl
 end if

 ! molpro/bdf --> molekel
 if(imode(5) == 1) then
   if(ipro == 0) then
     call rw_bas_molpro(ibas,imkl,0,maxlq,natom,nshell,infshl,tag,ctmp)
   else if(ipro == 1) then
     call rw_bas_bdf(ibas,imkl,0,maxlq,natom,nshell,infshl,tag,ctmp)
   end if
   call symmap(ipro,2,igrp,irrep)
   call basmap_mkl(maxlq,nshell,infshl,ntotbs,infobs,ibmap)
   loff = 0
   do isym = 1, nsym
     isym1 = irrep(isym)
     if(nbas(isym1) < 1) cycle
     moff = 0
     noff = 0
     do i = 1, isym1-1
       moff = moff + nbas(i)
       noff = noff + nbas(i)**2
     end do
     call reorderbs_mkl(nbas(isym1),ntotbs,ibmap(moff+1),occ1(moff+1),occtmp(loff+1),cmo(noff+1),cmofull(1,loff+1),scr)
     loff = loff + nbas(isym1)
   end do
   ! now, MOs saved in cmofull are in column vector

   ! print MOs in $COEFF_ALPHA & $OCC_ALPHA sections
   ! MOs are grouped according to inactive, active, and imag.
   call wr_mos_mkl(imkl,ntotbs,nsym,nbas,occtmp,occ2,cmofull,scr)
   call wr_occ_end(3,imkl,ntotbs,nsym,nbas,occ2)
   close(imkl)
 end if

 ! molpro/bdf --> molden
 if(imode(6) == 1) then
   if(maxlq > 6) call XError('Only s/p/d/f/g/h functions are supported for Molden format.')
   if(ipro == 0) then
     call rw_bas_molpro(ibas,imdn,1,maxlq,natom,nshell,infshl,tag,ctmp)
   else if(ipro == 1) then
     call rw_bas_bdf(ibas,imdn,1,maxlq,natom,nshell,infshl,tag,ctmp)
   end if
   call symmap(ipro,2,igrp,irrep)
   call basmap_mkl(maxlq,nshell,infshl,ntotbs,infobs,ibmap)
   loff = 0
   do isym = 1, nsym
     isym1 = irrep(isym)
     if(nbas(isym1) < 1) cycle
     moff = 0
     noff = 0
     do i = 1, isym1-1
       moff = moff + nbas(i)
       noff = noff + nbas(i)**2
     end do
     call reorderbs_mkl(nbas(isym1),ntotbs,ibmap(moff+1),occ1(moff+1),occ2(loff+1),cmo(noff+1),cmofull(1,loff+1),scr)
     loff = loff + nbas(isym1)
   end do
   ! now, MOs saved in cmofull are in column vector
   call wr_mos_mdn(imdn,igrp,ntotbs,nsym,nbas,irrep,occ2,cmofull,tag)
   close(imdn)
 end if

 if(imode(5) == 1 .or. imode(6) == 1) then
   deallocate(infshl, occtmp, cmofull)
   close(ibas,status='delete')
 end if

 ! new molpro/bdf
 ! This step is always performed last due to modifications to the MOs.
 if(imode(1) == 1) then
   call pr_head_new(ipro,inew,ctmp)
   inquire(unit=iopr,opened=ifopen)
   if(ifopen) then
     call orbopr(iopr,nsym,nbas,cmo,ctmp)
     close(iopr)
   end if
   noff = 0
   do isym = 1, nsym
     ! BDF: MO coefficients should be in column vector
     if(ipro == 1) call motran(nbas(isym),cmo(noff+1))
     call wr_mos(ipro,inew,isym,nbas(isym),cmo(noff+1))
     noff = noff + nbas(isym)**2
   end do
   call wr_occ_end(ipro,inew,ntotbs,nsym,nbas,occ1)
   close(inew)
 end if

 deallocate(cmo,occ1,occ2,scr,irrep,ibmap,infobs)

end program orbtran2

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! print MOs in the molden format.
! It doesn't work for symmetry equivalent atoms.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine wr_mos_mdn(imdn,igrp,norb,nsym,nbas,irrep,occ,cmo,symbol)
 implicit double precision (a-h,o-z)
 dimension :: nbas(nsym), irrep(nsym), occ(norb), cmo(norb,norb)
 character*(3) :: symbol(*)

 call set_irrep_symbol(igrp,symbol)

 write(imdn,"('[MO]')")
 iorb = 0
 do isym = 1, nsym
   isym1 = irrep(isym)
   do ibas = 1, nbas(isym1)
     iorb = iorb + 1
     write(imdn,"('Sym=',5x,a3)") symbol(isym)
     write(imdn,"('Ene=',f18.6)") 0.0d0
     write(imdn,"('Spin=    alpha')")
     write(imdn,"('Occup=',f16.6)") occ(iorb)
     do i = 1, norb
       write(imdn,"(i5,f22.16)") i, cmo(i,iorb)
     end do
   end do
 end do
 write(imdn,*)

 return
end subroutine wr_mos_mdn

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! print MOs in the mkl format.
! It doesn't work for symmetry equivalent atoms.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine wr_mos_mkl(imkl,norb,nsym,nbas,occ1,occ2,cmo,scr)
 implicit double precision (a-h,o-z)
 parameter(tol=1.0d-20)
 dimension :: nbas(nsym), occ1(norb), occ2(norb), cmo(norb,norb), scr(norb,norb)

 loff = 0

 ! inactive MOs
 do isym = 1, nsym
   if(nbas(isym) < 1) cycle
   moff = 0
   noff = 0
   do i = 1, isym-1
     moff = moff + nbas(i)
     noff = noff + nbas(i)**2
   end do
   do iorb = 1, nbas(isym)
     if(abs(occ1(moff+iorb)-2.0d0) <= tol) then
       loff = loff + 1
       occ2(loff) = occ1(moff+iorb)
       scr(:,loff) = cmo(:,moff+iorb)
     end if
   end do
 end do

 ! active MOs
 do isym = 1, nsym
   if(nbas(isym) < 1) cycle
   moff = 0
   noff = 0
   do i = 1, isym-1
     moff = moff + nbas(i)
     noff = noff + nbas(i)**2
   end do
   do iorb = 1, nbas(isym)
     if(abs(occ1(moff+iorb)-2.0d0) > tol .and. abs(occ1(moff+iorb)) > tol) then
       loff = loff + 1
       occ2(loff) = occ1(moff+iorb)
       scr(:,loff) = cmo(:,moff+iorb)
     end if
   end do
 end do

 ! imag. MOs
 do isym = 1, nsym
   if(nbas(isym) < 1) cycle
   moff = 0
   noff = 0
   do i = 1, isym-1
     moff = moff + nbas(i)
     noff = noff + nbas(i)**2
   end do
   do iorb = 1, nbas(isym)
     if(abs(occ1(moff+iorb)) <= tol) then
       loff = loff + 1
       occ2(loff) = occ1(moff+iorb)
       scr(:,loff) = cmo(:,moff+iorb)
     end if
   end do
 end do
 if(loff /= norb) call XError("loff .ne. norb in sub. wr_mos_mkl")

 nblk = (norb+4)/5
 write(imkl,"('$COEFF_ALPHA')")
 do iblk = 1, nblk
   loff = 5*(iblk-1)
   write(imkl,"(5a12)") ("a1g", j=loff+1, min(loff+5,norb))
   write(imkl,"(5f12.6)") (0.0d0, j=loff+1, min(loff+5,norb))
   do i = 1, norb
     write(imkl,"(5f22.16)") (scr(i,j), j=loff+1, min(loff+5,norb))
   end do
 end do
 write(imkl,"(' $END',/)")

 return
end subroutine wr_mos_mkl

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! read Molpro's basis functions and save them in Molekel (ifmt=0) or Molden (ifmt=1) format.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine rw_bas_molpro(ibas,imkl,ifmt,maxlq,natom,nshell,infshl,tag,ctmp)
 implicit double precision (a-h,o-z)
 parameter(au2ang=0.529177249d0)
 character*(*) tag,ctmp
 character*(3) :: atoms
 character*(1) :: alq
 dimension     :: infshl(2,*)
 allocatable   :: iza(:), xyz(:,:)
 allocatable   :: nprims(:), nconts(:), nfunc(:), ioffs(:), iadr(:), minl(:), icent(:)
 allocatable   :: aexp(:), acon(:), scr(:), alq(:)

 allocate(iza(natom), xyz(3,natom))

 rewind(ibas)
 rewind(imkl)

 read(ibas,*)
 ntot = 0
 do i = 1, natom
   read(ibas,*) atoms, iza(i), xyz(:,i)
   ntot = ntot + iza(i)
 end do
 xyz = au2ang * xyz

 if(ifmt == 0) then
   write(imkl,"('$MKL',/,'#',/,'# MKL format file produced by OrbTran-II.',/,'#')")
   write(imkl,"('$CHAR_MULT')")
   write(imkl,"(2i3)") 0, mod(ntot,2)+1
   write(imkl,"('$END')")
   write(imkl,*)

   write(imkl,"('$COORD')")
   do i = 1, natom
     write(imkl,"(i5,3f18.9)") iza(i), xyz(:,i)
   end do
   write(imkl,"('$END')")
   write(imkl,*)

   write(imkl,"('$CHARGES')")
   do i = 1, natom
     write(imkl,"(f11.6)") 0.0d0
   end do
   write(imkl,"('$END')")
   write(imkl,*)

   write(imkl,"('$BASIS')")
 else if(ifmt == 1) then
   write(imkl,"('[Molden Format]')")
   write(imkl,"('[Title]')")
   write(imkl,"(' Generated by OrbTran-II.')")
   write(imkl,"('[N_Atoms]')")
   write(imkl,"(i5)") natom
   write(imkl,"('[Atoms] Angs')")
   do i = 1, natom
     call ElemZA(1,atoms,iza(i))
     write(imkl,"(a3,3x,2i5,3x,3f18.9)") atoms, i, iza(i), xyz(:,i)
   end do
   if(maxlq > 2) write(imkl,"('[5D]')")
   if(maxlq > 3) write(imkl,"('[7F]')")
   if(maxlq > 4) write(imkl,"('[9G]')")
   if(maxlq > 5) write(imkl,"('[11H]')")
   write(imkl,"('[GTO]')")
 end if

 tag="# BAS"
 do while(.true.)
   read(ibas,"(a200)") ctmp
   if(index(ctmp,tag(1:5)) == 1) exit
 end do
 read(ibas,*) ngrp

 allocate(nprims(ngrp), nconts(ngrp), nfunc(ngrp), ioffs(ngrp), iadr(ngrp), minl(ngrp), icent(ngrp))
 nexp = 0
 ncon = 0
 do igrp = 1, ngrp
   read(ibas,"(5x,4i8,8x,2i8,16x,i8,8x,i8)") nprims(igrp), nconts(igrp), nfunc(igrp), ioffs(igrp), iadr(igrp),  &
     minl(igrp), icent(igrp), neqa
   if(nfunc(igrp) /= nconts(igrp)*(2*minl(igrp)+1)) call XError('Cartesian basis functions are not supported!')
   if(neqa > 1) call XError('Symmetry equivalent atoms are not supported! You have to use a lower symmetry.')
   nexp = nexp + nprims(igrp)
   ncon = ncon + nprims(igrp) * nconts(igrp)
 end do

 allocate(aexp(nexp), acon(ncon), scr(100), alq(7))

 tag=" Group"
 igrp = 0
 do while(.true.)
   read(ibas,"(a200)") ctmp
   if(index(ctmp,tag(1:6)) == 1) then
     igrp = igrp + 1
     call rd_group(ibas,ifmt,nprims(igrp),nconts(igrp),aexp(ioffs(igrp)+1),acon(iadr(igrp)),minl(igrp),scr)
   end if
   if(igrp == ngrp) exit
 end do

 alq = (/'S','P','D','F','G','H','I'/)
 nshell = 0
 do iatom = 1, natom
   iatom0 = 0
   do igrp = 1, ngrp
     ! the same element with different basis sets can lead to errors.
     if(iza(icent(igrp)) == iza(iatom)) then
       iatom0 = icent(igrp)
       exit
     end if
   end do
   if(iatom0 == 0) call XError('Some atoms have no basis functions!')
   if(ifmt == 1) write(imkl,"(i4,2x,'0')") iatom
   do igrp = 1, ngrp
     if(iatom0 == icent(igrp)) then
       call wr_group(imkl,ifmt,minl(igrp),alq,nprims(igrp),nconts(igrp), aexp(ioffs(igrp)+1),acon(iadr(igrp)))
       do icon = 1, nconts(igrp)
         nshell = nshell + 1
         infshl(1,nshell) = iatom
         infshl(2,nshell) = minl(igrp)
       end do
     end if
   end do
   if(ifmt == 0) then
     if(iatom < natom) then
       write(imkl,"('$$')")
     else
       write(imkl,*)
     end if
   else if(ifmt == 1) then
     write(imkl,*)
   end if
 end do

 if(ifmt == 0) write(imkl,"('$END')")
 write(imkl,*)

 deallocate(iza, xyz)
 deallocate(aexp, acon, scr, alq)
 deallocate(nprims, nconts, nfunc, ioffs, iadr, minl, icent)

 return
end subroutine rw_bas_molpro

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! read BDF's basis functions and save them in Molekel (ifmt=0) or Molden (ifmt=1) format.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine rw_bas_bdf(ibas,imkl,ifmt,maxlq,natom,nshell,infshl,tag,ctmp)
 implicit double precision (a-h,o-z)
 parameter(au2ang=0.529177249d0)
 character*(*) tag,ctmp
 character*(3) :: atoms
 character*(1) :: alq
 dimension     :: infshl(2,*)
 allocatable   :: iza(:), xyz(:,:)
 allocatable   :: nconts(:), ioffs(:), minl(:), icent(:)
 allocatable   :: aexp(:), acon(:), scr(:), alq(:)

 allocate(iza(natom), xyz(3,natom))

 rewind(ibas)
 rewind(imkl)

 read(ibas,*)
 ntot = 0
 do i = 1, natom
   read(ibas,*) atoms, iza(i), xyz(:,i)
   ntot = ntot + iza(i)
 end do
 xyz = au2ang * xyz

 if(ifmt == 0) then
   write(imkl,"('$MKL',/,'#',/,'# MKL format file produced by OrbTran-II.',/,'#')")
   write(imkl,"('$CHAR_MULT')")
   write(imkl,"(2i3)") 0, mod(ntot,2)+1
   write(imkl,"('$END')")
   write(imkl,*)

   write(imkl,"('$COORD')")
   do i = 1, natom
     write(imkl,"(i5,3f18.9)") iza(i), xyz(:,i)
   end do
   write(imkl,"('$END')")
   write(imkl,*)

   write(imkl,"('$CHARGES')")
   do i = 1, natom
     write(imkl,"(f11.6)") 0.0d0
   end do
   write(imkl,"('$END')")
   write(imkl,*)

   write(imkl,"('$BASIS')")
 else if(ifmt == 1) then
   write(imkl,"('[Molden Format]')")
   write(imkl,"('[Title]')")
   write(imkl,"(' Generated by OrbTran-II.')")
   write(imkl,"('[N_Atoms]')")
   write(imkl,"(i5)") natom
   write(imkl,"('[Atoms] Angs')")
   do i = 1, natom
     call ElemZA(1,atoms,iza(i))
     write(imkl,"(a3,3x,2i5,3x,3f18.9)") atoms, i, iza(i), xyz(:,i)
   end do
   if(maxlq > 2) write(imkl,"('[5D]')")
   if(maxlq > 3) write(imkl,"('[7F]')")
   if(maxlq > 4) write(imkl,"('[9G]')")
   if(maxlq > 5) write(imkl,"('[11H]')")
   write(imkl,"('[GTO]')")
 end if

 tag="# BAS"
 do while(.true.)
   read(ibas,"(a200)") ctmp
   if(index(ctmp,tag(1:5)) == 1) exit
 end do
 ! #shell
 nshell = 0
 ncon = 0
 do while(.true.)
   read(ibas,"(a200)",err=1000,end=1000) ctmp
   ! Only element names and angular momentum symbols start from the first column.
   if(ctmp(1:1) == ' ') cycle
   ! The length of element name is at least 3 (Tin)
   if(ctmp(2:2) /= ' ') cycle
   if(ctmp(1:1) == 'S' .or. ctmp(1:1) == 'P' .or. ctmp(1:1) == 'D' .or. ctmp(1:1) == 'F' .or.   &
      ctmp(1:1) == 'G' .or. ctmp(1:1) == 'H' .or. ctmp(1:1) == 'I') then
     read(ctmp(2:),*) i
     nshell = nshell + 1
     ncon = ncon + i
   end if
 end do

 1000 continue
 if(nshell == 0) call XError('nshell = 0 in sub. rw_bas_bdf.')
 if(ncon == 0) call XError('ncon = 0 in sub. rw_bas_bdf.')

 rewind(ibas)
 allocate(aexp(ncon), acon(ncon), scr(100), alq(7))
 allocate(nconts(nshell), ioffs(nshell), minl(nshell), icent(nshell))

 do while(.true.)
   read(ibas,"(a200)") ctmp
   if(index(ctmp,tag(1:5)) == 1) exit
 end do
 ishell = 0
 ioffs(1) = 0
 do while(.true.)
   read(ibas,"(a200)",err=2000,end=2000) ctmp
   ! search the element name
   if(ctmp(1:1) /= ' ' .and. ctmp(2:2) /= ' ' .and. ctmp(3:3) /= ' ') then
     call elementname(ctmp, izatom)
     if(izatom == 0) then
       write(*,"(a)") trim(ctmp)
       call XError('Unknown element name in sub. rw_bas_bdf.')
     end if

     do while(.true.)
       read(ibas,"(a200)",err=2000,end=2000) ctmp
       if(len_trim(ctmp) == 0) exit

       ishell = ishell + 1
       select case(ctmp(1:1))
         case('S')
           minl(ishell) = 0
         case('P')
           minl(ishell) = 1
         case('D')
           minl(ishell) = 2
         case('F')
           minl(ishell) = 3
         case('G')
           minl(ishell) = 4
         case('H')
           minl(ishell) = 5
         case('I')
           call XError('orca_2mkl has a problem with -mkl and LQ = 6.')
         case default
           call XError('Unknown LQ in sub. rw_bas_bdf.')
       end select
       read(ctmp(2:),*) nconts(ishell)
       icent(ishell) = izatom
       if(ishell > 1) ioffs(ishell) = ioffs(ishell-1) + nconts(ishell-1)
       do icon = 1, nconts(ishell)
         read(ibas,*,err=2000,end=2000) i, aexp(ioffs(ishell)+icon), acon(ioffs(ishell)+icon)
       end do
       ! renormalization
       call renorm(minl(ishell),nconts(ishell),1,aexp(ioffs(ishell)+1),acon(ioffs(ishell)+1),scr)
       if(ifmt == 0) then
         ! ORCA uses non-standard normalization factors
         do icon = 1, nconts(ishell)
           cf=fnorm(aexp(ioffs(ishell)+icon),minl(ishell))
           acon(ioffs(ishell)+icon) = acon(ioffs(ishell)+icon) * cf * scalorca(minl(ishell))
         end do
       end if
     end do
   end if
 end do

 2000 continue
 alq = (/'S','P','D','F','G','H','I'/)

 do iatom = 1, natom
   izatom0 = 0
   do ishell = 1, nshell
     ! the same element with different basis sets can lead to errors.
     if(icent(ishell) == iza(iatom)) then
       izatom0 = icent(ishell)
       exit
     end if
   end do
   if(izatom0 == 0) call XError('Some atoms have no basis functions!')
   if(ifmt == 1) write(imkl,"(i4,2x,'0')") iatom
   do ishell = 1, nshell
     if(izatom0 == icent(ishell)) then
       call wr_group(imkl,ifmt,minl(ishell),alq,nconts(ishell),1,aexp(ioffs(ishell)+1),acon(ioffs(ishell)+1))
       infshl(1,ishell) = iatom
       infshl(2,ishell) = minl(ishell)
     end if
   end do
   if(ifmt == 0) then
     if(iatom < natom) then
       write(imkl,"('$$')")
     else
       write(imkl,*)
     end if
   else if(ifmt == 1) then
     write(imkl,*)
   end if
 end do

 if(ifmt == 0) write(imkl,"('$END')")
 write(imkl,*)

 deallocate(iza, xyz)
 deallocate(aexp, acon, scr, alq)
 deallocate(nconts, ioffs, minl, icent)

 return
end subroutine rw_bas_bdf

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! write a basis group in mkl/molden format
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine wr_group(imkl,ifmt,lq,alq,np,nc,aexp,acon)
 implicit real(kind=8) (a-h,o-z)
 parameter(tol=1.0d-12)
 character*(1) :: alq(0:6)
 dimension :: aexp(np), acon(np,nc)

 if(ifmt == 0) then
   do ic = 1, nc
     write(imkl,"(i3,1x,a1,' 1.0')") lq+lq+1, alq(lq)
     do ip = 1, np
       if(abs(acon(ip,ic)) > 1.0d-12) write(imkl,"(2f24.10)") aexp(ip), acon(ip,ic)
     end do
   end do
 else if(ifmt == 1) then
   do ic = 1, nc
     np0 = 0
     do ip = 1, np
       if(abs(acon(ip,ic)) > tol) np0 = np0 + 1
     end do
     write(imkl,"(3x,a1,i5,2x,'1.0')") alq(lq), np0
     do ip = 1, np
       if(abs(acon(ip,ic)) > tol) write(imkl,"(2e24.12)") aexp(ip), acon(ip,ic)
     end do
   end do
 end if

 return
end subroutine wr_group

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! read a basis group
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine rd_group(ibas,ifmt,np,nc,aexp,acon,lq,scr)
 implicit real(kind=8) (a-h,o-z)
 dimension :: aexp(np), acon(np,nc), scr(100)

 do ip = 1, np
   read(ibas,*) aexp(ip), acon(ip,:)
 end do

 ! renormalization
 call renorm(lq,np,nc,aexp,acon,scr)

 ! mkl: ORCA uses non-standard normalization factors
 if(ifmt == 0) then
   do ip = 1, np
     cf=fnorm(aexp(ip),lq)
     acon(ip,:) = acon(ip,:) * cf * scalorca(lq)
   end do
 end if

 return
end subroutine rd_group

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! scaling factors for turbomole & orca
! lq         factor
! s,p,h :  * 1.0
! d     :  * sqrt(3)
! f     :  * sqrt(15)
! g     :  * sqrt(105)
! i     :  unknown
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function scalorca(lq)
 implicit real(kind=8) (a-h,o-z)

 select case(lq)
   case(0,1,5)
     a=1.d0
   case(2)
     a=sqrt(3.d0)
   case(3)
     a=sqrt(15.d0)
   case(4)
     a=sqrt(105.d0)
   case(6)
     call XError('orca_2mkl has a problem with -mkl and LQ = 6.')
   case default
     call XError('LQ > 6 in func. scalorca.')
 end select

 scalorca = a

 return
end function scalorca

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! calculate the normalization factor for GTO(L)
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
function fnorm(ex,lq)
 implicit real(kind=8) (a-h,o-z)
 parameter (pi=acos(-1.0d0),pi3=pi*pi*pi)

 ! Normal^4 = 2^n1 * a^n2 / (pi^3 * nf), where n1=3+4*L; n2=3+2*L, nf=[(2L-1)!!]^2
 call power(lq,n1,n2,nf)
 f = (2.d0**dble(n1)) * (ex**dble(n2)) / (pi3 * dble(nf))
 fnorm=sqrt(sqrt(f))

 return
end function fnorm

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! renormalize contracted GTFs for a given Lq
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine renorm(lq,ngauss,ncon,alf,con,scr)
 implicit real(kind=8) (a-h,o-z)
 parameter (tol=1.0d-10,pi=acos(-1.0d0),pi3=pi*pi*pi)
 dimension         :: alf(ngauss),con(ngauss,ncon),scr(ngauss)

 ! unnormalize primitives
 ! Normal^4 = 2^n1 * a^n2 / (pi^3 * nf)
 !   n1=3+4*L; n2=3+2*L, nf=[(2L-1)!!]^2
 call power(lq,n1,n2,nf)
 fc = (2.0d0**dble(n1)) / (pi3 * dble(nf))
 do icon = 1, ncon
   do i = 1,ngauss
     f = fc * (alf(i)**dble(n2))
     scr(i) = con(i,icon)*sqrt(sqrt(f))
   end do

   fsum = 0.0d0
   do i = 1,ngauss
     do j = 1,i
       f = (alf(i)+alf(j)) * 0.5d0
       f = fc * (f**dble(n2))
       f = scr(i)*scr(j)/sqrt(f)
       if (i /= j) f = f + f
       fsum = fsum + f
     end do
   end do

   if (fsum > tol) fsum = 1.0d0 / sqrt(fsum)
   con(:,icon) = con(:,icon) * fsum
 end do

 return
end subroutine renorm

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! get power(n1,n2,nf) for GTO(L) normalization
! n1=3+4*L; n2=3+2*L, nf=[(2L-1)!!]^2
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine power(lq,n1,n2,nf)
 implicit real(kind=8) (a-h,o-z)

 select case(lq)
   case(0)
     n1=3
     n2=3
     nf=1
   case(1)
     n1=7
     n2=5
     nf=1
   case(2)
     n1=11
     n2=7
     nf=9
   case(3)
     n1=15
     n2=9
     nf=225
   case(4)
     n1=19
     n2=11
     nf=11025
   case(5)
     n1=23
     n2=13
     nf=893025
   case(6)
     call XError('orca_2mkl has a problem with -mkl and LQ = 6.')
     n1=27
     n2=15
     nf=108056025
   case default
     call XError('LQ > 6 in sub. power.')
 end select

 return
end subroutine power

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! do MO operations: e[x]change, [c]lean, [s]et, and [S]et. For example,
! x isym imo1 imo2    ! exchange imo1.isym imo2.isym
! c isym imo          ! clean imo.isym
! p isym imo          ! change the phase of imo.isym
! P isym imo          ! print the coefficients of imo.isym
! s isym imo ic val   ! set the ic-th coefficient in imo.isym to val
! S isym imo ic val   ! clean imo.isym and set the ic-th coefficient to val
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine orbopr(iopr,nsym,nbas,cmo,ctmp)
 implicit double precision (a-h,o-z)
 dimension :: nbas(nsym), cmo(*)
 character*(200) ctmp

 noff = 0
 do isym = 1, nsym
   call motran(nbas(isym),cmo(noff+1))
   noff = noff + nbas(isym)**2
 end do

 rewind(iopr)
 do while(.true.)
   read(iopr,"(a200)",end=1000) ctmp
   if(len_trim(ctmp) == 0) exit
   istr=nonspace(ctmp)
   if(ctmp(istr:istr) == 'c') then
     call opr_mocp(nsym,nbas,cmo,1,ctmp(istr+1:200))
   else if(ctmp(istr:istr) == 'p') then
     call opr_mocp(nsym,nbas,cmo,2,ctmp(istr+1:200))
   else if(ctmp(istr:istr) == 'P') then
     call opr_mocp(nsym,nbas,cmo,3,ctmp(istr+1:200))
   else if(ctmp(istr:istr) == 's') then
     call opr_mos(nsym,nbas,cmo,ctmp(istr+1:200))
   else if(ctmp(istr:istr) == 'S') then
     call opr_mocs(nsym,nbas,cmo,ctmp(istr+1:200))
   else if(ctmp(istr:istr) == 'x') then
     call opr_mox(nsym,nbas,cmo,ctmp(istr+1:200))
   end if
 end do
 1000 continue

 noff = 0
 do isym = 1, nsym
   call motran(nbas(isym),cmo(noff+1))
   noff = noff + nbas(isym)**2
 end do

 return
end subroutine orbopr

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! Set a value of an MO.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine opr_mos(nsym,nbas,cmo,ctmp)
 implicit double precision (a-h,o-z)
 dimension nbas(nsym), cmo(*)
 character*(*)  :: ctmp

 read(ctmp,*) isym, imo, ic, va
 if(isym < 1 .or. isym > nsym) call XError("isym of MO in [s] is out of range!")
 if(imo < 1 .or. imo > nbas(isym)) call XError("imo of MO in [s] is out of range!")
 if(ic < 1 .or. ic > nbas(isym)) call XError("ic of MO in [s] is out of range!")

 ioff = 0
 do i = 1, isym-1
   norb = nbas(i)
   ndat = norb * norb
   ioff = ioff + ndat
 end do
 norb = nbas(isym)
 ndat = norb * (imo - 1)
 ioff = ioff + ndat

 cmo(ioff+ic) = va

 return
end subroutine opr_mos

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! imod
!  = 1  clean an MO
!  = 2  change the phase of an MO
!  = 3  print an MO
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine opr_mocp(nsym,nbas,cmo,imod,ctmp)
 implicit double precision (a-h,o-z)
 dimension nbas(nsym), cmo(*)
 character*(*)  :: ctmp

 read(ctmp,*) isym, imo
 if(isym < 1 .or. isym > nsym) call XError("isym of MO in [c] is out of range!")
 if(imo < 1 .or. imo > nbas(isym)) call XError("imo of MO in [c] is out of range!")

 ioff = 0
 do i = 1, isym-1
   norb = nbas(i)
   ndat = norb * norb
   ioff = ioff + ndat
 end do
 norb = nbas(isym)
 ndat = norb * (imo - 1)
 ioff = ioff + ndat

 if(imod == 1) then
   cmo(ioff+1:ioff+norb) = 0.0d0
 else if(imod == 2) then
   cmo(ioff+1:ioff+norb) = -cmo(ioff+1:ioff+norb)
 else if(imod == 3) then
   write(*,"(/,' isym = ',i1,', MO = ',i3)") isym, imo
   write(*,"(10f10.4)") (cmo(ioff+i), i=1,norb)
 end if

 return
end subroutine opr_mocp

