!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! irrep symbols in BDF/Orca ordering.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine set_irrep_symbol(igrp,symbol)
 implicit double precision (a-h,o-z)
 character*(3) :: symbol(*)

 select case(igrp)
   case(1)  ! C1
     symbol(1:1) = (/'  a'/)
   case(2)  ! Cs
     symbol(1:2) = (/" a'", ' a"'/)
   case(3)  ! C2
     symbol(1:2) = (/'  a', '  b'/)
   case(4)  ! Ci
     symbol(1:2) = (/' ag', ' au'/)
   case(5)  ! C2v
     symbol(1:4) = (/' a1', ' a2',' b1',' b2'/)
   case(6)  ! C2h
     symbol(1:4) = (/' ag', ' bg',' au',' bu'/)
   case(7)  ! D2
     symbol(1:4) = (/'  a', ' b1',' b2',' b3'/)
   case(8)  ! D2h
     symbol(1:8) = (/' ag', 'b1g','b2g','b3g',' au','b1u','b2u','b3u'/)
 end select

 return
end subroutine set_irrep_symbol

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! reorder irreps:
! ipro = 0: Molpro -> BDF(0)/Molcas(1)/Orca(2)
! ipro = 1: BDF -> Molpro(0)/Molcas(1)/Orca(2)
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine symmap(ipro,Imode,igrp,irrep)
 implicit double precision (a-h,o-z)
 dimension :: irrep(*)

 if(ipro == 0) then
   if(Imode == 0 .or. Imode == 2) then
     select case(igrp)
       case(1)  ! C1
         !     Molpro:    a
         !   BDF/Orca:    a
         irrep(1:1) = (/  1/)
       case(2)  ! Cs
         !     Molpro:   a'  a"
         !   BDF/Orca:   a'  a"
         irrep(1:2) = (/  1,  2/)
       case(3)  ! C2
         !     Molpro:    a   b
         !   BDF/Orca:    a   b
         irrep(1:2) = (/  1,  2/)
       case(4)  ! Ci
         !     Molpro:   ag  au
         !   BDF/Orca:   ag  au
         irrep(1:2) = (/  1,  2/)
       case(5)  ! C2v
         !     Molpro:   a1  b1  b2  a2
         !   BDF/Orca:   a1  a2  b1  b2
         irrep(1:4) = (/  1,  4,  2,  3/)
       case(6)  ! C2h
         !     Molpro:   ag  au  bu  bg
         !   BDF/Orca:   ag  bg  au  bu
         irrep(1:4) = (/  1,  4,  2,  3/)
       case(7)  ! D2
         !     Molpro:    a  b3  b2  b1
         !   BDF/Orca:    a  b1  b2  b3  (Ver. >= 2023.3.12)
         irrep(1:4) = (/  1,  4,  3,  2/)
       case(8)  ! D2h
         !     Molpro:   ag b3u b2u b1g b1u b2g b3g  au
         !   BDF/Orca:   ag b1g b2g b3g  au b1u b2u b3u  (Ver. >= 2023.3.12)
         irrep(1:8) = (/  1,  4,  6,  7,  8,  5,  3,  2/)
     end select
   else if(Imode == 1) then
     select case(igrp)
       case(1)  ! C1
         !     Molpro:    a
         !     Molcas:    a
         irrep(1:1) = (/  1/)
       case(2)  ! Cs
         !     Molpro:   a'  a"
         !     Molcas:   a'  a"
         irrep(1:2) = (/  1,  2/)
       case(3)  ! C2
         !     Molpro:    a   b
         !     Molcas:    a   b
         irrep(1:2) = (/  1,  2/)
       case(4)  ! Ci
         !     Molpro:   ag  au
         !     Molcas:   ag  au
