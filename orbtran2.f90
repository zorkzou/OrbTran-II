         !     Molpro:   ag  au  bu  bg
         !     Molcas:   ag  bu  au  bg
         irrep(1:4) = (/  1,  3,  2,  4/)
       case(7)  ! D2
         !     Molpro:    a  b3  b2  b1
         !     Molcas:    a  b3  b2  b1, but labelled as:   a  b2  b1  b3
         ! irrep(1:4) = (/  1,  3,  4,  2/)
         irrep(1:4) = (/  1,  2,  3,  4/)
       case(8)  ! D2h
         !     Molpro:   ag b3u b2u b1g b1u b2g b3g  au
         !     Molcas:   ag b3u b2u b1g b1u b2g b3g  au
         irrep(1:8) = (/  1,  2,  3,  4,  5,  6,  7,  8/)
     end select
   else
     call XError("Unknown Imode in sub. symmap.")
   end if
 else if(ipro == 1) then
   if(Imode == 0) then
     select case(igrp)
       case(1)  ! C1
         !        BDF:    a
         !     Molpro:    a
         irrep(1:1) = (/  1/)
       case(2)  ! Cs
         !        BDF:   a'  a"
         !     Molpro:   a'  a"
         irrep(1:2) = (/  1,  2/)
       case(3)  ! C2
         !        BDF:    a   b
         !     Molpro:    a   b
         irrep(1:2) = (/  1,  2/)
       case(4)  ! Ci
         !        BDF:   ag  au
         !     Molpro:   ag  au
         irrep(1:2) = (/  1,  2/)
       case(5)  ! C2v
         !        BDF:   a1  a2  b1  b2
         !     Molpro:   a1  b1  b2  a2
         irrep(1:4) = (/  1,  3,  4,  2/)
       case(6)  ! C2h
         !        BDF:   ag  bg  au  bu
         !     Molpro:   ag  au  bu  bg
         irrep(1:4) = (/  1,  3,  4,  2/)
       case(7)  ! D2
         !        BDF:    a  b1  b2  b3  (Ver. >= 2023.3.12)
         !     Molpro:    a  b3  b2  b1
         irrep(1:4) = (/  1,  4,  3,  2/)
       case(8)  ! D2h
         !        BDF:   ag b1g b2g b3g  au b1u b2u b3u  (Ver. >= 2023.3.12)
         !     Molpro:   ag b3u b2u b1g b1u b2g b3g  au
         irrep(1:8) = (/  1,  8,  7,  2,  6,  3,  4,  5/)
     end select
   else if(Imode == 1) then
     select case(igrp)
       case(1)  ! C1
         !        BDF:    a
         !     Molcas:    a
         irrep(1:1) = (/  1/)
       case(2)  ! Cs
         !        BDF:   a'  a"
         !     Molcas:   a'  a"
         irrep(1:2) = (/  1,  2/)
       case(3)  ! C2
         !        BDF:    a   b
         !     Molcas:    a   b
         irrep(1:2) = (/  1,  2/)
       case(4)  ! Ci
         !        BDF:   ag  au
         !     Molcas:   ag  au
         irrep(1:2) = (/  1,  2/)
       case(5)  ! C2v
         !        BDF:   a1  a2  b1  b2
         !     Molcas:   a1  b1  b2  a2
         irrep(1:4) = (/  1,  3,  4,  2/)
       case(6)  ! C2h
         !        BDF:   ag  bg  au  bu
         !     Molcas:   ag  bu  au  bg
         irrep(1:4) = (/  1,  4,  3,  2/)
       case(7)  ! D2
         !        BDF:    a  b1  b2  b3  (Ver. >= 2023.3.12)
         !     Molcas:    a  b3  b2  b1, but labelled as:   a  b2  b1  b3
         ! irrep(1:4) = (/  1,  3,  2,  4/)
         irrep(1:4) = (/  1,  4,  3,  2/)
       case(8)  ! D2h
         !        BDF:   ag b1g b2g b3g  au b1u b2u b3u  (Ver. >= 2023.3.12)
         !     Molcas:   ag b3u b2u b1g b1u b2g b3g  au
         irrep(1:8) = (/  1,  8,  7,  2,  6,  3,  4,  5/)
     end select
   else if(Imode == 2) then
     select case(igrp)
       case(1)    ! C1
         irrep(1:1) = (/  1/)
       case(2:4)  ! Cs,C2,Ci
         irrep(1:2) = (/  1,  2/)
       case(5:7)  ! C2v,C2h,D2
         irrep(1:4) = (/  1,  2,  3,  4/)
       case(8)    ! D2h
         irrep(1:8) = (/  1,  2,  3,  4,  5,  6,  7,  8/)
     end select
   else
     call XError("Unknown Imode in sub. symmap.")
   end if
 else
   call XError("Unknown ipro in sub. symmap.")
 end if

 return
end subroutine symmap

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! check Molpro's mcscf log file: natom, symmetry, nbas, and save a new output file for the istp-th step.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine chk_molpro(ilog,iorb,natom,nsym,nbas,igrp,istp,tag,ctmp)
 implicit double precision (a-h,o-z)
 character*(*) tag, ctmp
 dimension nbas(8)

 open(iorb,file="morb.tmp")
 rewind(iorb)
 rewind(ilog)

 do while(.true.)
   read(ilog,"(a200)",err=6010,end=6010) ctmp
   if(index(ctmp," Point group  ") == 1) exit
 end do
 nsym = 0
 select case(ctmp(15:17))
   case("D2h")
     igrp = 8
     nsym = 8
   case("D2 ")
     igrp = 7
     nsym = 4
   case("C2h")
     igrp = 6
     nsym = 4
   case("C2v")
     igrp = 5
     nsym = 4
   case("Ci ")
     igrp = 4
     nsym = 2
   case("C2 ")
     igrp = 3
     nsym = 2
   case("Cs ")
     igrp = 2
     nsym = 2
   case("C1 ")
     igrp = 1
     nsym = 1
 end select
 if(nsym == 0) call XError("Check the point group!")

 tag='NR  ATOM    CHARGE       X              Y              Z'
 natom = 0
 loop1 : do while(.true.)
   read(ilog,"(a200)",err=6110,end=6110) ctmp
   if(index(ctmp,tag(1:56)) /= 0) then
     read(ilog,*)
     loop2 : do while(.true.)
       read(ilog,"(a200)",err=6120,end=6120) ctmp
       if(len_trim(ctmp) == 0) exit loop1
       natom = natom + 1
     end do loop2
   end if
 end do loop1

 tag=' NUMBER OF CONTRACTIONS: '
 do while(.true.)
   read(ilog,"(a200)",err=6210,end=6210) ctmp
   if(index(ctmp,tag(1:25)) == 1) exit
 end do
 nbas = 0
 do irep=1, nsym
   i1 = 32 + irep*10
   i2 = i1 + 4
   !write(*,"(2i4,a5)")i1,i2,ctmp(i1:i2)
   read(ctmp(i1:i2),"(i5)") nbas(irep)
 end do

 tag = " PROGRAM * MULTI (Direct Multiconfiguration SCF)       Authors: P.J. Knowles, H.-J. Werner (1984)"
 imc = 0
 rewind(ilog)
 do while(.true.)
   read(ilog,"(a200)",err=500,end=500) ctmp
   if(ctmp(1:97) == tag(1:97)) imc = imc + 1
   if(imc == istp) exit
 end do
 500  continue
 if(imc < istp) call XError("The specified MCSCF output is not found in chk_molpro!")

 tag=' PSEUDO CANONICAL ORBITALS'
 do while(.true.)
   read(ilog,"(a200)",err=6310,end=6310) ctmp
   if(index(ctmp,tag(1:26)) > 0) exit
 end do

 ! save MO information to iorb
 tag=' **************************************************'
 do while(.true.)
   read(ilog,"(a200)",err=6320,end=6320) ctmp
   if(index(ctmp,tag(1:51)) > 0) exit
   write(iorb,"(a)") trim(ctmp)
 end do

 return

 6010  call XError("No point group found!")
 6110  call XError("No Cartesian coordinates found!")
 6120  call XError("Check the Cartesian coordinates!")
 6210  call XError("No number of contractions found!")
 6310  call XError("No canonical MO information found!")
 6320  call XError("No basis (l,m) information found!")
end subroutine chk_molpro

