! check BDF's mcscf log file: natom, symmetry, nbas, and save a new output file for the istp-th step.
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine chk_bdf(ilog,iorb,natm,nsym,nbas,igrp,istp,tag,ctmp)
 implicit double precision (a-h,o-z)
 character*(*) tag,ctmp
 dimension nbas(8)

 open(iorb,file="morb.tmp")
 rewind(iorb)
 rewind(ilog)

 tag=" Number of atoms: "
 do while(.true.)
   read(ilog,"(a200)",err=6010,end=6010) ctmp
   if(index(ctmp,tag(1:18)) == 1) exit
 end do
 read(ctmp(19:),*) natm

 do while(.true.)
   read(ilog,"(a200)",err=6110,end=6110) ctmp
   if(index(ctmp,"[molesym]") > 0) exit
 end do
 ! nosymm?
 read(ilog,"(/,a10)",err=6110,end=6110) ctmp
 if(index(ctmp,"C|1|)|") > 0) then
   ctmp(27:31) = "C(1) "
 else
   tag="User set point group as"
   do while(.true.)
     read(ilog,"(a200)",err=6120,end=6120) ctmp
     if(index(ctmp,tag(1:23)) > 0) exit
   end do
 end if

 nsym = 0
 select case(ctmp(27:31))
   case("D(2H)")
     igrp = 8
     nsym = 8
   case("D(2) ")
     igrp = 7
     nsym = 4
   case("C(2H)")
     igrp = 6
     nsym = 4
   case("C(2V)")
     igrp = 5
     nsym = 4
   case("C(I) ")
     igrp = 4
     nsym = 2
   case("C(2) ")
     igrp = 3
     nsym = 2
   case("C(S) ")
     igrp = 2
     nsym = 2
   case("C(1) ")
     igrp = 1
     nsym = 1
 end select
 if(nsym == 0) call XError("Non-Abelian symmetry is not supported!")

 tag="Number of irreps:"
 do while(.true.)
