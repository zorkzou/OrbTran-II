!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! Exchange two MOs
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine opr_mox(nsym,nbas,cmo,ctmp)
 implicit double precision (a-h,o-z)
 dimension nbas(nsym), cmo(*)
 character*(*)  :: ctmp
 allocatable   :: scr(:)

 read(ctmp,*) isym, imo1, imo2
 if(isym < 1 .or. isym > nsym) call XError("isym of MO in [x] is out of range!")
 if(imo1 < 1 .or. imo1 > nbas(isym)) call XError("imo1 of MO in [x] is out of range!")
 if(imo2 < 1 .or. imo2 > nbas(isym)) call XError("imo2 of MO in [x] is out of range!")

 ioff = 0
 do i = 1, isym-1
   norb = nbas(i)
   ndat = norb * norb
   ioff = ioff + ndat
 end do
 norb = nbas(isym)
 allocate(scr(norb))

 ioff1 = ioff + norb * (imo1 - 1)
 ioff2 = ioff + norb * (imo2 - 1)

 scr = cmo(ioff1+1:ioff1+norb)
 cmo(ioff1+1:ioff1+norb) = cmo(ioff2+1:ioff2+norb)
 cmo(ioff2+1:ioff2+norb) = scr

 deallocate(scr)
 return
end subroutine opr_mox

