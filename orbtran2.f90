 do while(.true.)
   read(ilog,"(a200)",err=6140,end=6140) ctmp
   if(index(ctmp,"  Norb  :") > 0) exit
 end do
 nbas = 0
 read(ctmp(10:),*) (nbas(irep), irep=1, nsym)

 tag="    ******** MCSCF solver ********"
 imc = 0
 do while(.true.)
   read(ilog,"(a34)",err=500,end=500) ctmp
   if(index(ctmp,tag(1:34)) > 0) then
     imc = imc + 1
     if(imc == istp) exit
   end if
 end do
 500  continue
 if(imc < istp) call XError("The specified MCSCF output is not found in subroutine chk_bdf!")
 tag=" Print CMO informations = "
 do while(.true.)
   read(ilog,"(a48)",err=6210,end=6210) ctmp
   if(index(ctmp,tag(1:26)) > 0) then
     read(ctmp(27:48),*) lq
     if(lq < 2) call XError("MCSCF: Iprtmo should be 2 at least!")
     exit
   end if
 end do

 ! save MO information to iorb
 tag='TARGET_MCSCF ROOT ENERGY'
 do while(.true.)
   read(ilog,"(a200)",err=6220,end=6220) ctmp
   if(index(ctmp,tag(1:24)) > 0) exit
   write(iorb,"(a)") trim(ctmp)
 end do

 return

 6010  call XError("No number of atoms found!")
 6110  call XError("No [molesym] found!")
 6120  call XError("No point group found!")
 6130  call XError("No number of irreps found!")
 6140  call XError("No number of orbitals found!")
 6210  call XError("MCSCF: No print level of MO found!")
 6220  call XError("No basis (l,m) information found!")
end subroutine chk_bdf

