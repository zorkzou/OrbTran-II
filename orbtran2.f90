!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! read MCSCF pseudo canonical orbitals and occupation numbers from BDF's casorb file
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine mos_bdf(imos,ntotbs,nsym,nbas,cmo,occ,tag,ctmp)
 implicit double precision (a-h,o-z)
 character*(*) tag,ctmp
 dimension :: nbas(nsym), cmo(*), occ(ntotbs)

 rewind(imos)

 ioff = 0
 tag="SYM=NORB="
 do isym = 1, nsym
   loop2 : do while(.true.)
     read(imos,"(a100)",err=6010,end=6010) ctmp
