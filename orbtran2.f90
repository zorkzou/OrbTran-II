!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! read gto pattern from BDF's log file
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine rd_patt_bdf(ilog,igto,nsym,nbas,tag,ctmp)
 implicit double precision (a-h,o-z)
 character*(*) tag,ctmp
 dimension nbas(nsym)

 rewind(ilog)
 open(igto,file="bfun.tmp")
 rewind(igto)

 tag="  Symmetry   "
 do irep = 1, nsym
   do while(.true.)
     read(ilog,"(a13)",err=6120,end=6120) ctmp
     if(index(ctmp,tag(1:13)) > 0) exit
   end do
   read(ilog,"(///)",err=6120,end=6120)
   do ibs = 1, nbas(irep)
     read(ilog,"(a17)",err=6130,end=6130) ctmp
     ! position of s,p,d,f... after "|"
     ipl = 11 + ipos_lett(ctmp(12:17))
     ctmp(10:17) = '   ' // ctmp(ipl:17) // ' '
     call treatpatt(ctmp(8:15))
     write(igto,"(2x,a8)") ctmp(8:15)
   end do
 end do

 return

 6120  call XError("MCSCF: No Symmetry found!")
 6130  call XError("MCSCF: No GTO pattern found!")

 contains

 ! position of the first letter after "|"
 function ipos_lett(cha)
   character*(*) cha

   n = len(cha)
   ipos_lett = 0
   do i = 1, n
     if( ( ichar(cha(i:i)) >= 65 .and. ichar(cha(i:i)) <= 90 ) .or. &
         ( ichar(cha(i:i)) >= 97 .and. ichar(cha(i:i)) <=122 ) ) then
       ipos_lett = i
       exit
     end if
   end do

   return
 end function ipos_lett

 ! gto pattern to molpro format
 subroutine treatpatt(cha)
   implicit double precision (a-h,o-z)
   character*(8) cha

   cha(2:3) = cha(1:2)
   cha(1:1) = ' '

   call charu2l(cha)

   lq = 0
   select case(cha(6:6))
     case("s")
       lq = 1
     case("p")
       lq = 2
     case("d")
       lq = 3
     case("f")
       lq = 4
     case("g")
       lq = 5
     case("h")
       lq = 6
     case("i")
       lq = 7
   end select
   if(lq == 0) call XError("MCSCF: Unsupported GTO found!")
   write(cha(4:5),"(i2)") lq

   cha(6:6) = ' '
   if(cha(7:7) /= '-') then
     cha(8:8) = cha(7:7)
     cha(7:7) = ' '
   end if

   return
 end subroutine treatpatt

end subroutine rd_patt_bdf

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! read gto pattern and occupation numbers from Molpro's log file
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine rd_patt_molpro(iorb,igto,ntotbs,nsym,nbas,occ,tag,ctmp)
 implicit double precision (a-h,o-z)
 character*(*) tag,ctmp
 dimension nbas(nsym), occ(ntotbs)

 occ = 0.0d0

 open(igto,file="bfun.tmp")
 rewind(igto)
 !write(igto,"('### 1')")
 rewind(iorb)

 tag="   Orb     Occ        Energy       Coefficients"
 do while(.true.)
   read(iorb,"(a200)",err=6010,end=6010) ctmp
   if(index(ctmp,tag(1:47)) > 0) exit
 end do
 ioff = 0
 do while(.true.)
   read(iorb,"(a131)",err=6110,end=6110) ctmp
   if(len_trim(ctmp(1:131)) == 0) then
     cycle
   else if(len_trim(ctmp(1:31)) == 0) then
     if(index(ctmp(32:131),'s') /= 0 .or. index(ctmp(32:131),'p') /= 0 .or. index(ctmp(32:131),'d') /= 0 .or. &
        index(ctmp(32:131),'f') /= 0 .or. index(ctmp(32:131),'g') /= 0 .or. index(ctmp(32:131),'h') /= 0 .or. &
        index(ctmp(32:131),'i') /= 0) then
       aline = dble( len_trim(ctmp(32:131)) ) * 0.1d0
       call wrgto10(igto,nint(aline),ctmp(32:))
     else if(index(ctmp(32:131),'j') /= 0 .or. index(ctmp(32:131),'k') /= 0) then
       call XError("Only spdfghi functions are supported!")
     end if
     cycle
   end if
   read(ctmp(1:15),"(f6.1,f9.5)",err=1000) a1, a2
   imo = int(a1)
   isym= mod(nint(a1*10.d0),10)
   if(imo == 1) then
     !if(isym == nsym) then
     !  write(igto,"('### 0')")
     !else
     !  write(igto,"('###',i2)") isym+1
     !end if
     if(isym > 1) ioff = ioff + nbas(isym-1)
   end if
   occ(ioff+imo) = a2
 end do

 1000  continue
 if(isym < nsym) then
   write(*,"(/,' MOs in one irrep are not printed. Using',/,'   orbprint,nvirt=1',/,' may solve this problem.')")
   call XError(" ")
 end if

 return

 6010  call XError("No MO data found! Orbprint should be specified in the MULTI module with gthresh,thrprint=0.")
 6110  call XError("No Orb & Occ numbers found!")

 contains

 ! write gto information in the format of 10 characters per line
 subroutine wrgto10(igto,n,ctmp)
  implicit double precision (a-h,o-z)
  character*(10) ctmp(n)

  do i10 = 1, n
    ! read(ctmp(i10),"(i5,i2)") iatm, ilq
    call getlm(ctmp(i10)(8:10),ilm)
    write(igto,"(a5,1x,a2,i4)") ctmp(i10)(1:5), ctmp(i10)(6:7), ilm
  end do

  return
 end subroutine wrgto10
end subroutine rd_patt_molpro

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! get lm from characters
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine getlm(chabas,ilm)
 implicit double precision (a-h,o-z)
 character*(3) :: chabas

 select case(chabas)
   case("s  ","pz ","d0 ","f0 ","g0 ","h0 ","i0 ")
     ilm =  0
   case("py ","d1-","f1-","g1-","h1-","i1-")
     ilm = -1
   case("px ","d1+","f1+","g1+","h1+","i1+")
     ilm =  1
   case("d2-","f2-","g2-","h2-","i2-")
     ilm = -2
   case("d2+","f2+","g2+","h2+","i2+")
     ilm =  2
   case("f3-","g3-","h3-","i3-")
     ilm = -3
   case("f3+","g3+","h3+","i3+")
     ilm =  3
   case("g4-","h4-","i4-")
     ilm = -4
   case("g4+","h4+","i4+")
     ilm =  4
   case("h5-","i5-")
     ilm = -5
   case("h5+","i5+")
     ilm =  5
   case("i6-")
     ilm = -6
   case("i6+")
     ilm =  6
   case default
     write(*,"(/,a)") chabas
     call XError("Unknown basis function!")
 end select

 return
end subroutine getlm

