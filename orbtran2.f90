end subroutine save_bas_bdf

!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
!
! Arguments.
!
! -PRO   The output file and mcscf wf file are produced by Molpro or BDF.
!        Default: determined by the canonical_mo_coeff file (see -MOS).
!
! -PRO   Molpro (ipro = 0)
! ------------------------
! read:
!  -LOG                    Molpro's mcscf_log_file.           # Default: mcscf.out
!  -n N                    the N-th MCSCF output in LOG       # Default: N = 1
!  -MOS                    Molpro's canonical_mo_coeff_file.  # Default: mcscf.casorb
!  -OPR                    a file for orbital operations      # No default. see subroutine orbopr
!                          (it affects only -NEW)
! write:
!  -OUT:MOLCAS   (= -RAS)  Molcas RASSCF coeff. file.         # No default
!  -OUT:BDF      (= -BDF)  BDF MCSCF coeff. file.             # No default
!  -OUT:MOLEKEL  (= -MKL)  MOLEKEL file used by ORCA.         # No default
!  -OUT:MOLDEN   (= -MDN)  MOLDEN file.                       # No default
!  -OUT:NEW      (= -NEW)  New Molpro MCSCF coeff. file.      # Default: new_mcscf.casorb if -OPR is specified
!
! -PRO   BDF (ipro = 1)
! ---------------------
! read:
!  -LOG                    BDF's mcscf_log_file.              # Default: mcscf.out
!  -n N                    the N-th MCSCF output in LOG       # Default: N = 1
!  -MOS                    BDF's canonical_mo_coeff_file.     # Default: mcscf.casorb
!  -OPR                    a file for orbital operations      # No default
!                          (it affects only -NEW)
! write:
!  -OUT:MOLCAS   (= -RAS)  Molcas RASSCF coeff. file.         # No default
!  -OUT:MOLPRO   (= -MOL)  MOLPRO MCSCF coeff. file.          # No default
!  -OUT:MOLEKEL  (= -MKL)  MOLEKEL file used by ORCA.         # No default
!  -OUT:MOLDEN   (= -MDN)  MOLDEN file.                       # No default
!  -OUT:NEW      (= -NEW)  New BDF MCSCF coeff. file.         # Default: new_mcscf.casorb if -OPR is specified
!
!%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
subroutine RdArg(ipro,ilog,imos,iopr,inew,iras,ibdf,imol,imkl,imdn,i_stp,nmode,imode,ctmp)
 implicit real(kind=8) (a-h,o-z)
 dimension :: imode(nmode)
 character*200 :: ctmp
 logical :: ifopen, ifexist

 i_stp = 1
 ipro  =-1
 imode = 0
 ! 1 £ºnew Molpro or BDF
 ! 2 : Molpro/BDF to Molcas
 ! 3 : Molpro to BDF
 ! 4 : BDF to Molpro
 ! 5 : Molpro/BDF to Molekel
 ! 6 : Molpro/BDF to Molden

 i = 0
 do while(.true.)
   i = i + 1
   call Get1Cmd(i,.True.,ctmp)
   istr=nonspace(ctmp)
   iend=len_trim(ctmp)

   if(iend == 0) then
     exit
   else if(ctmp(istr:iend) == '-PRO') then
     i = i + 1
     call Get1Cmd(i,.true.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(ctmp(istr:iend) == 'MOLPRO') then
       ipro = 0
     else if(ctmp(istr:iend) == 'BDF') then
       ipro = 1
     end if
   else if(ctmp(istr:iend) == '-LOG') then
     i = i + 1
     call Get1Cmd(i,.False.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(iend == 0) then
       call XError("No file name provided for -LOG.")
     else
       inquire(file=ctmp(istr:iend),opened=ifopen,exist=ifexist)
       call chkfile(ctmp(istr:iend),1,ifopen,1,ifexist)
       open(ilog,file=ctmp(istr:iend),status='old',iostat=ist)
       if(ist /= 0) then
         write(*,"(/,' File: ',a)") ctmp(istr:iend)
         call XError("Cannot open mcscf log file.")
       end if
     end if
   else if(ctmp(istr:iend) == '-MOS') then
     i = i + 1
     call Get1Cmd(i,.False.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(iend == 0) then
       call XError("No file name provided for -MOS.")
     else
       inquire(file=ctmp(istr:iend),opened=ifopen,exist=ifexist)
       call chkfile(ctmp(istr:iend),1,ifopen,1,ifexist)
       open(imos,file=ctmp(istr:iend),status='old',iostat=ist)
       if(ist /= 0) then
         write(*,"(/,' File: ',a)") ctmp(istr:iend)
         call XError("Cannot open mcscf canonical MO file.")
       end if
     end if
   else if(ctmp(istr:iend) == '-OPR') then
     i = i + 1
     call Get1Cmd(i,.False.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(iend == 0) then
       call XError("No file name provided for -OPR.")
     else
       inquire(file=ctmp(istr:iend),opened=ifopen,exist=ifexist)
       call chkfile(ctmp(istr:iend),1,ifopen,1,ifexist)
       open(iopr,file=ctmp(istr:iend),status='old',iostat=ist)
       if(ist /= 0) then
         write(*,"(/,' File: ',a)") ctmp(istr:iend)
         call XError("Cannot open the orbital operation file.")
       end if
     end if
   else if(ctmp(istr:iend) == '-N') then
     i = i + 1
     call Get1Cmd(i,.False.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(iend == 0) then
       call XError("i_stp is not provided for -N.")
     else
       call chknumber(-1,ctmp(istr:iend))
       read(ctmp(istr:iend),*) i_stp
       if(i_stp < 1) i_stp = 1
     end if
   !-----------------------------------------------------------
   ! -OUT:KEYWORD
   !-----------------------------------------------------------
   else if(ctmp(istr:iend) == '-OUT:NEW' .or. ctmp(istr:iend) == '-NEW') then
     i = i + 1
     call Get1Cmd(i,.False.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(iend == 0) then
       call XError("No file name provided for -OUT:NEW.")
     else
       inquire(file=ctmp(istr:iend),opened=ifopen,exist=ifexist)
       call chkfile(ctmp(istr:iend),1,ifopen,0,ifexist)
       open(inew,file=ctmp(istr:iend),iostat=ist)
       if(ist /= 0) then
         write(*,"(/,' File: ',a)") ctmp(istr:iend)
         call XError("Cannot creat new mcscf file.")
       end if
     end if
     imode(1) = 1
   else if(ctmp(istr:iend) == '-OUT:MOLCAS' .or. ctmp(istr:iend) == '-RAS') then
     i = i + 1
     call Get1Cmd(i,.False.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(iend == 0) then
       call XError("No file name provided for -OUT:MOLCAS.")
     else
       inquire(file=ctmp(istr:iend),opened=ifopen,exist=ifexist)
       call chkfile(ctmp(istr:iend),1,ifopen,0,ifexist)
       open(iras,file=ctmp(istr:iend),iostat=ist)
       if(ist /= 0) then
         write(*,"(/,' File: ',a)") ctmp(istr:iend)
         call XError("Cannot creat Molcas RasOrb file.")
       end if
     end if
     imode(2) = 1
   else if(ctmp(istr:iend) == '-OUT:BDF' .or. ctmp(istr:iend) == '-BDF') then
     i = i + 1
     call Get1Cmd(i,.False.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(iend == 0) then
       call XError("No file name provided for -OUT:BDF.")
     else
       inquire(file=ctmp(istr:iend),opened=ifopen,exist=ifexist)
       call chkfile(ctmp(istr:iend),1,ifopen,0,ifexist)
       open(ibdf,file=ctmp(istr:iend),iostat=ist)
       if(ist /= 0) then
         write(*,"(/,' File: ',a)") ctmp(istr:iend)
         call XError("Cannot creat the BDF mcscf file.")
       end if
     end if
     imode(3) = 1
   else if(ctmp(istr:iend) == '-OUT:MOLPRO' .or. ctmp(istr:iend) == '-MOL') then
     i = i + 1
     call Get1Cmd(i,.False.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(iend == 0) then
       call XError("No file name provided for -OUT:MOLPRO.")
     else
       inquire(file=ctmp(istr:iend),opened=ifopen,exist=ifexist)
       call chkfile(ctmp(istr:iend),1,ifopen,0,ifexist)
       open(imol,file=ctmp(istr:iend),iostat=ist)
       if(ist /= 0) then
         write(*,"(/,' File: ',a)") ctmp(istr:iend)
         call XError("Cannot creat the Molpro mcscf file.")
       end if
     end if
     imode(4) = 1
   else if(ctmp(istr:iend) == '-OUT:MOLEKEL' .or. ctmp(istr:iend) == '-MKL') then
     i = i + 1
     call Get1Cmd(i,.False.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(iend == 0) then
       call XError("No file name provided for -OUT:MOLEKEL.")
     else
       inquire(file=ctmp(istr:iend),opened=ifopen,exist=ifexist)
       call chkfile(ctmp(istr:iend),1,ifopen,0,ifexist)
       open(imkl,file=ctmp(istr:iend),iostat=ist)
       if(ist /= 0) then
         write(*,"(/,' File: ',a)") ctmp(istr:iend)
         call XError("Cannot creat the Molekel file.")
       end if
     end if
     imode(5) = 1
   else if(ctmp(istr:iend) == '-OUT:MOLDEN' .or. ctmp(istr:iend) == '-MDN') then
     i = i + 1
     call Get1Cmd(i,.False.,ctmp)
     istr=nonspace(ctmp)
     iend=len_trim(ctmp)
     if(iend == 0) then
       call XError("No file name provided for -OUT:MOLDEN.")
     else
       inquire(file=ctmp(istr:iend),opened=ifopen,exist=ifexist)
       call chkfile(ctmp(istr:iend),1,ifopen,0,ifexist)
       open(imdn,file=ctmp(istr:iend),iostat=ist)
       if(ist /= 0) then
         write(*,"(/,' File: ',a)") ctmp(istr:iend)
         call XError("Cannot creat the Molden file.")
       end if
     end if
     imode(6) = 1
   else
     call XError("Unknown argument "//ctmp(istr:iend))
   end if
 end do

 inquire(unit=ilog,opened=ifopen)
   if(.NOT.ifopen) then
     ! -LOG is not defined
     inquire(file="mcscf.out",opened=ifopen,exist=ifexist)
     call chkfile("mcscf.out",1,ifopen,1,ifexist)
     open(ilog,file="mcscf.out",status='old',iostat=ist)
     if(ist /= 0) call XError("Cannot open the file mcscf.out.")
   end if
 inquire(unit=imos,opened=ifopen)
   if(.NOT.ifopen) then
     ! -MOS is not defined
     inquire(file="mcscf.casorb",opened=ifopen,exist=ifexist)
     call chkfile("mcscf.casorb",1,ifopen,1,ifexist)
     open(imos,file="mcscf.casorb",status='old',iostat=ist)
     if(ist /= 0) call XError("Cannot open the file mcscf.casorb.")
   end if
 inquire(unit=iopr,opened=ifopen)
   if(ifopen) then
     inquire(unit=inew,opened=ifopen)
     if(.NOT.ifopen) then
       ! new mcscf casorb file
       inquire(file="new_mcscf.casorb",opened=ifopen,exist=ifexist)
       call chkfile("new_mcscf.casorb",1,ifopen,0,ifexist)
       open(inew,file="new_mcscf.casorb",iostat=ist)
       if(ist /= 0) call XError("Cannot creat the file new_mcscf.casorb.")
       imode(1) = 1
     end if
   end if

 if(ipro == -1) call chkpro(ipro,imos,ctmp)

 if(ipro == 0) then
   inquire(unit=imol,opened=ifopen)
   if(ifopen) call XError("-MOL cannot be used for -PRO molpro.")
 else if(ipro == 1) then
   inquire(unit=ibdf,opened=ifopen)
   if(ifopen) call XError("-BDF cannot be used for -PRO bdf.")
 else
   call XError("Unknown program name!")
 end if

 return

